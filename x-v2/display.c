void LoadSerialBMP(void) {
	uint8_t *pui_pic1 = (uint8_t*)g_pui32DisplayBuffer + 0x4b000;
	uint8_t *pui_pic2 = (uint8_t*)g_pui32DisplayBuffer + 0x4b000 + 0x4b000;

	UARTConfigSetExpClk(UART0_BASE, g_ui32SysClock, 230400, (UART_CONFIG_WLEN_8 | UART_CONFIG_STOP_ONE | UART_CONFIG_PAR_NONE));

	uint8_t x = 2;
	uint8_t *pui_framebuffer;
	while (x--) {
		// nacteni hlavicky BMP
		for (ui32Row = 0; ui32Row < 70; ui32Row++) {
			scr_data = UARTCharGet(UART0_BASE);
		}
		pui_framebuffer = (uint8_t*)g_pui32DisplayBuffer;
		for (ui32Row = 0; ui32Row < (LCD_HORIZONTAL_MAX * LCD_VERTICAL_MAX * 2); ui32Row++) {
			// nacteni bitmapy
			scr_data = UARTCharGet(UART0_BASE);
			*pui_framebuffer++ = scr_data;
		}
		pui_framebuffer = (uint8_t*)g_pui32DisplayBuffer;
		if (x == 0) memcpy(pui_pic1, pui_framebuffer, 0x4b000);
		if (x == 1) memcpy(pui_pic2, pui_framebuffer, 0x4b000);
	}

	uint32_t ui32ClockMS = g_ui32SysClock / (12 * 1000);

	while (1) {
		pui_framebuffer = (uint8_t*)g_pui32DisplayBuffer;
		memcpy(pui_framebuffer, pui_pic1, 0x4b000);
		MAP_SysCtlDelay(2000 * ui32ClockMS);
		pui_framebuffer = (uint8_t*)g_pui32DisplayBuffer;
		memcpy(pui_framebuffer, pui_pic2, 0x4b000);
		MAP_SysCtlDelay(2000 * ui32ClockMS);
	}

}
