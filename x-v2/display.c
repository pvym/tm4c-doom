int16_t aSin[512];
uint16_t colors[256];

void InitSin(void) {
	int i;
	float rad;

	/*create sin lookup table */
	for (i = 0; i < 512; i++)
	{
		rad =  ((float)i * 0.703125) * 0.0174532; /* 360 / 512 * degree to rad, 360 degrees spread over 512 values to be able to use AND 512-1 instead of using modulo 360*/
		aSin[i] = ((int16_t)(sin(rad) * 1024)); /*using fixed point math with 1024 as base*/
	}

	/* create palette */
	for (i = 0; i < 64; ++i)
	{
		colors[i] = (i << 2) | ((255 - ((i << 2) + 1)) << 8);
		colors[i+64] = 255 | (((i << 2) + 1) << 8);
		colors[i+128] = (255 - ((i << 2) + 1)) | ((255 - ((i << 2) + 1)) << 8);
		colors[i+192] = (i << 2) + 1;
	}

}

